#!/usr/bin/env python3
"""Pack an assets/ tree into a flat blob + a C++ index, for portable builds.

    python3 tools/embed_assets.py --assets ../game/public/assets \\
            --game hollowmere --out /tmp/build-hollowmere

Writes
    <out>/assets_blob.bin    every file, concatenated (linked in with ld -r -b binary)
    <out>/assets_index.cpp   the lookup table + vfs:: implementation

Directory entries are added too (length 0) so the game's "is there an assets
folder?" probes answer yes without touching the disk. A root-level game.txt is
added as well, which is how the executable knows which campaign it is.
"""
import argparse
import os
import sys

HEADER = """// ---------------------------------------------------------------------------
//  assets_index.cpp — generated by tools/embed_assets.py, do not edit.
//
//  %(nfiles)d files (%(nmb).1f MB) from %(root)s baked into the executable.
//  Campaign: %(game)s
//
//  The bytes live in assets_blob.bin, which the linker turns into an object file
//  with `ld -r -b binary`; this file only carries the directory.
// ---------------------------------------------------------------------------
#include "vfs.h"
#include <cstring>
#include <string>
#include <unordered_map>

#if defined(_WIN32)
extern "C" const unsigned char _binary_assets_blob_bin_start[];
#else
extern "C" const unsigned char _binary_assets_blob_bin_start[];
#endif

namespace {

const unsigned char* kBlob = _binary_assets_blob_bin_start;

struct Entry {
  const char* key;      // lower-case, '/'-separated, relative to the assets root
  unsigned offset;      // into kBlob
  unsigned size;        // 0 for a directory
};

const Entry kEntries[] = {
%(entries)s
};

constexpr int kEntryCount = (int)(sizeof(kEntries) / sizeof(kEntries[0]));

// ---- lookup --------------------------------------------------------------
// Keys are matched by *suffix*: the game may ask for "assets/characters/Knight.glb"
// or "C:/Games/Hollowmere/assets/characters/Knight.glb" and both find
// "characters/knight.glb".  Built once, on first use.
std::string normalize(const std::string& path) {
  std::string p;
  p.reserve(path.size());
  for (char c : path) {
    if (c == '\\\\') c = '/';
    else if (c >= 'A' && c <= 'Z') c = (char)(c - 'A' + 'a');
    p.push_back(c);
  }
  // strip "./" prefixes and duplicate slashes
  std::string q;
  q.reserve(p.size());
  for (size_t i = 0; i < p.size(); i++) {
    if (p[i] == '/' && !q.empty() && q.back() == '/') continue;
    q.push_back(p[i]);
  }
  while (q.size() >= 2 && q[0] == '.' && q[1] == '/') q.erase(0, 2);
  while (!q.empty() && q[0] == '/') q.erase(0, 1);
  while (!q.empty() && q.back() == '/') q.pop_back();
  return q;
}

const std::unordered_map<std::string, const Entry*>& table() {
  static std::unordered_map<std::string, const Entry*> map = [] {
    std::unordered_map<std::string, const Entry*> m;
    m.reserve(kEntryCount * 2);
    for (int i = 0; i < kEntryCount; i++) m.emplace(kEntries[i].key, &kEntries[i]);
    return m;
  }();
  return map;
}

const Entry* find(const std::string& path) {
  if (kEntryCount == 0) return nullptr;
  std::string p = normalize(path);
  const auto& map = table();
  // longest suffix first, then walk up one component at a time
  size_t pos = 0;
  for (;;) {
    auto it = map.find(p.substr(pos));
    if (it != map.end()) return it->second;
    size_t slash = p.find('/', pos);
    if (slash == std::string::npos) break;
    pos = slash + 1;
  }
  return nullptr;
}

}  // namespace

namespace vfs {

bool available() { return kEntryCount > 0; }
int count() { return kEntryCount; }

bool read(const std::string& path, std::vector<uint8_t>& out) {
  const Entry* e = find(path);
  if (!e || e->size == 0) return false;   // unknown, or a directory
  out.assign(kBlob + e->offset, kBlob + e->offset + e->size);
  return true;
}

bool exists(const std::string& path) { return find(path) != nullptr; }

}  // namespace vfs
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--assets", required=True, help="assets root to embed")
    ap.add_argument("--game", default="hollowmere")
    ap.add_argument("--out", required=True, help="output directory")
    args = ap.parse_args()

    root = os.path.abspath(args.assets)
    if not os.path.isdir(root):
        sys.exit("no such assets dir: " + root)
    os.makedirs(args.out, exist_ok=True)

    # collect (relative path, absolute path) for every non-empty file
    files = []
    dirs = set()
    for dirpath, dirnames, filenames in os.walk(root):
        rel_dir = os.path.relpath(dirpath, root).replace(os.sep, "/")
        if rel_dir != ".":
            dirs.add(rel_dir)
        for fn in sorted(filenames):
            p = os.path.join(dirpath, fn)
            if os.path.getsize(p) == 0:
                continue
            rel = fn if rel_dir == "." else rel_dir + "/" + fn
            files.append((rel, p))
    files.sort()

    blob_path = os.path.join(args.out, "assets_blob.bin")
    entries = []
    offset = 0
    total = 0
    with open(blob_path, "wb") as blob:
        # directories first (they are just markers)
        for d in sorted(dirs):
            entries.append((d.lower(), 0, 0))
        # then the root-level game.txt, which selects the campaign
        gt = ("game.txt\n" + args.game + "\n").encode()
        entries.append(("game.txt", offset, 0))
        # (patched below: game.txt has bytes, so write it like any other file)
        entries.pop()
        blob.write(gt)
        entries.append(("game.txt", offset, len(gt)))
        offset += len(gt)
        total += len(gt)

        for rel, path in files:
            data = open(path, "rb").read()
            blob.write(data)
            entries.append((rel.lower(), offset, len(data)))
            offset += len(data)
            total += len(data)

    # sanity: no duplicate keys
    seen = {}
    for key, _, _ in entries:
        if key in seen:
            sys.exit("duplicate asset key: " + key)
        seen[key] = True

    lines = []
    for key, off, size in entries:
        lines.append('    {"%s", %d, %d},' % (key, off, size))

    cpp_path = os.path.join(args.out, "assets_index.cpp")
    with open(cpp_path, "w") as fh:
        fh.write(HEADER % dict(entries="\n".join(lines), nfiles=len(entries),
                               nmb=total / 1e6, root=root, game=args.game))

    print("%-12s %5d entries  %6.1f MB -> %s" % (args.game, len(entries), total / 1e6, blob_path))


if __name__ == "__main__":
    main()
